    let translations = translationsStore[currentLang] || translationsStore.ru;

    function translate(key, params = {}) {
        const keys = key.split('.');
        let value = keys.reduce((obj, k) => obj?.[k], translations);
        if (value === undefined) {
            console.warn(`Missing translation: ${key}`);
            return key;
        }
        if (typeof value === 'string') {
            Object.entries(params).forEach(([k, v]) => {
                value = value.replace(new RegExp(`{${k}}`, 'g'), v);
            });
        }
        return value;
    }

    function translatePage() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            el.textContent = translate(key);
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            el.placeholder = translate(el.getAttribute('data-i18n-placeholder'));
        });
        document.querySelectorAll('[data-i18n-arch]').forEach(el => {
            const archKey = el.getAttribute('data-i18n-arch');
            let archId = el.closest('[data-arch-id]')?.getAttribute('data-arch-id') || 
                         window.location.pathname.match(/courses\/([^/]+)/)?.[1] || 
                         'monolit';
            const fullKey = `architectures.${archId}.${archKey}`;
            el.textContent = translate(fullKey);
        });
        document.documentElement.lang = currentLang;
        updateSwitcherUI();
    }

    async function setLanguage(lang) {
        if (lang === currentLang) return;
        if (translationsStore[lang]) {
            currentLang = lang;
            translations = translationsStore[lang];
            localStorage.setItem('lang', lang);
            translatePage();
        } else {
            console.error(`Language ${lang} not available`);
        }
    }

    function getCurrentLanguage() {
        return currentLang;
    }

    function updateSwitcherUI() {
        document.querySelectorAll('[data-lang]').forEach(el => {
            el.classList.toggle('active', el.getAttribute('data-lang') === currentLang);
        });
    }

    async function init() {
        translatePage();
    }

    return {
        init,
        setLanguage,
        getCurrentLanguage,
        translatePage,
        t: translate
    };
